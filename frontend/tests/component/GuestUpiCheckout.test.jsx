import { act, cleanup, renderHook, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import useUpiCheckout from '@features/enrollment/hooks/useUpiCheckout';
import { guestEnrollmentApi } from '@shared/services/guestEnrollmentApi';
import { upiPaymentApi } from '@shared/services/upiPaymentService';
import { readEnrollmentDraft } from '@features/enrollment/utils/enrollmentDraft';
import { guestStatusLink, readGuestStatusRecords } from '@features/enrollment/utils/guestStatusLink';
vi.mock('@shared/services/guestEnrollmentApi', () => ({ guestEnrollmentApi: { create: vi.fn(), paymentInfo: vi.fn(), submit: vi.fn(), status: vi.fn() } }));
vi.mock('@shared/services/upiPaymentService', () => ({ upiPaymentApi: { createEnrollment: vi.fn(), getPaymentInfo: vi.fn() }, loadEnrollmentState: vi.fn() }));
const courses = [{ id: 5, name: 'React', price: 5000 }];
const token = 'a'.repeat(64);
const student = { fullName: 'Asha Rao', email: 'asha@example.com', phone: '9876543210' };
const onAllSubmitted = vi.fn();
const options = { enabled: true, courses, guest: true, getStudent: () => student, getBatchId: () => '', onAllSubmitted };
beforeEach(() => {
  localStorage.clear();
  window.history.replaceState({}, '', '/enrollment?courseId=5');
  vi.clearAllMocks();
  guestEnrollmentApi.create.mockResolvedValue({ id: 42, guestAccessToken: token, amount: 4500 });
  guestEnrollmentApi.paymentInfo.mockResolvedValue({ upiId: 'institute@upi', payeeName: 'Institute', amount: 4500, qrCode: '/qr.png' });
  guestEnrollmentApi.submit.mockResolvedValue({ id: 9 });
  guestEnrollmentApi.status.mockResolvedValue({ stage: 'submitted', accountReady: false, enrollment: { id: 42 } });
});
afterEach(cleanup);
it('creates a guest application, loads institute UPI details, and submits proof without marking it verified', async () => {
  const { result } = renderHook(() => useUpiCheckout(options));
  await act(() => result.current.start());
  await waitFor(() => expect(result.current.info?.upiId).toBe('institute@upi'));
  expect(guestEnrollmentApi.create).toHaveBeenCalledWith(expect.objectContaining({ courseId: 5, student, batchId: '', idempotencyKey: expect.any(String) }));
  expect(upiPaymentApi.createEnrollment).not.toHaveBeenCalled();
  expect(guestEnrollmentApi.paymentInfo).toHaveBeenCalledWith(42, token);
  await act(() => result.current.submit({ utrNumber: '123456789012', screenshot: new File(['image'], 'proof.png', { type: 'image/png' }), amount: 4500 }));
  expect(guestEnrollmentApi.submit).toHaveBeenCalledWith(42, token, expect.objectContaining({ utrNumber: '123456789012' }), expect.any(String));
  expect(onAllSubmitted).toHaveBeenCalledOnce();
  expect(result.current.status.stage).toBe('submitted');
  expect(readEnrollmentDraft().upi.records[0]).toMatchObject({ enrollmentId: 42, paymentId: 9, guestAccessToken: token });
});
it('keeps the creation idempotency key when retrying a lost response', async () => {
  guestEnrollmentApi.create.mockRejectedValueOnce(new Error('Connection lost'));
  const { result } = renderHook(() => useUpiCheckout(options));
  await act(() => result.current.start());
  const key = guestEnrollmentApi.create.mock.calls[0][0].idempotencyKey;
  await act(() => result.current.start());
  expect(guestEnrollmentApi.create.mock.calls[1][0].idempotencyKey).toBe(key);
  await act(() => result.current.start());
  expect(guestEnrollmentApi.create).toHaveBeenCalledTimes(2);
});
it('reopens status with a fragment token and supports rejected proof correction with a new key', async () => {
  const link = guestStatusLink([{ courseId: 5, courseName: 'React', price: 5000, enrollmentId: 42, guestAccessToken: token }]);
  expect(new URL(link).search).toBe('');
  window.history.replaceState({}, '', link);
  expect(readGuestStatusRecords()[0].guestAccessToken).toBe(token);
  guestEnrollmentApi.status.mockResolvedValue({ stage: 'payment-rejected', accountReady: false, enrollment: { id: 42 }, rejectionReason: 'UTR does not match' });
  const { result } = renderHook(() => useUpiCheckout(options));
  await waitFor(() => expect(result.current.status.stage).toBe('payment-rejected'));
  act(() => result.current.resubmitRejected());
  expect(result.current.phase).toBe('paying');
  expect(result.current.current.rejection).toBe('UTR does not match');
  await waitFor(() => expect(result.current.info?.amount).toBe(4500));
  await act(() => result.current.submit({ utrNumber: '999999999999', screenshot: new File(['ok'], 'correct.png', { type: 'image/png' }), amount: 4500 }));
  expect(guestEnrollmentApi.submit).toHaveBeenCalledWith(42, token, expect.objectContaining({ utrNumber: '999999999999' }), expect.any(String));
});
it('continues checking approval until password setup makes the account ready', async () => {
  window.history.replaceState({}, '', guestStatusLink([{ courseId: 5, price: 5000, enrollmentId: 42, guestAccessToken: token }]));
  guestEnrollmentApi.status.mockResolvedValue({ stage: 'approved', accountReady: false, requiresPasswordSetup: true, enrollment: { id: 42 } });
  const { result } = renderHook(() => useUpiCheckout(options));
  await waitFor(() => expect(result.current.status.requiresPasswordSetup).toBe(true));
  expect(result.current.status.accountReady).toBe(false);
  guestEnrollmentApi.status.mockResolvedValue({ stage: 'approved', accountReady: true, enrollment: { id: 42 } });
  await act(() => result.current.refreshStatus());
  expect(result.current.status.accountReady).toBe(true);
});
