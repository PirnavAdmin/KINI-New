/**
 * Helper: searches, filters, sorts, and paginates mock employee data
 * to simulate the same behavior as the real API.
 */
export function queryMockEmployees({
  searchText = '',
  status = '',
  sortBy = 'FirstName',
  isDescending = false,
  pageNumber = 1,
  pageSize = 10,
} = {}) {
  let data = [...MOCK_EMPLOYEES]

  // Search
  if (searchText.trim()) {
    const q = searchText.toLowerCase()
    data = data.filter(
      (e) =>
        e.firstName.toLowerCase().includes(q) ||
        e.lastName.toLowerCase().includes(q) ||
        [e.firstName, e.lastName].filter(Boolean).join(' ').toLowerCase().includes(q) ||
        (e.employeeId || '').toLowerCase().includes(q) ||
        e.email.toLowerCase().includes(q)
    )
  }

  // Status filter
  if (status) {
    const target = status.toLowerCase()
    data = data.filter((e) => (e.status || '').toLowerCase() === target)
  }

  // Total before pagination
  const totalRecords = data.length

  // Sort
  const sortFieldMap = {
    EmployeeId: 'employeeId',
    FirstName: 'firstName',
    LastName: 'lastName',
    Name: 'firstName',
    Email: 'email',
    DepartmentId: 'departmentName',
    BranchId: 'branchName',
    Designation: 'designation',
    JoiningDate: 'joiningDate',
    Status: 'status',
  }
  const field = sortFieldMap[sortBy] || 'firstName'

  // Sort — handle dates specially
  const isDateField = field === 'joiningDate'
  data.sort((a, b) => {
    if (isDateField) {
      const aVal = new Date(a[field] || 0).getTime()
      const bVal = new Date(b[field] || 0).getTime()
      return isDescending ? bVal - aVal : aVal - bVal
    }
    const aVal = String(a[field] ?? '').toLowerCase()
    const bVal = String(b[field] ?? '').toLowerCase()
    if (aVal < bVal) return isDescending ? 1 : -1
    if (aVal > bVal) return isDescending ? -1 : 1
    return 0
  })

  // Paginate
  const totalPages = Math.max(1, Math.ceil(totalRecords / pageSize))
  const startIndex = (pageNumber - 1) * pageSize
  const pagedData = data.slice(startIndex, startIndex + pageSize)

  return {
    data: pagedData,
    totalRecords,
    totalPages,
    pageNumber,
    pageSize,
  }
}
