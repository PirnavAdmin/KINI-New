export const filterWebinars = (webinars, filters) => {
  let filtered = [...webinars]
  const { search, type, status, category, department } = filters

  if (search) {
    const q = search.toLowerCase()
    filtered = filtered.filter(
      (w) =>
        w.title.toLowerCase().includes(q) ||
        w.hostName.toLowerCase().includes(q) ||
        w.type.toLowerCase().includes(q) ||
        w.description.toLowerCase().includes(q) ||
        w.department.toLowerCase().includes(q) ||
        w.category.toLowerCase().includes(q)
    )
  }

  if (type && type !== 'All') {
    filtered = filtered.filter((w) => w.type === type)
  }

  if (status && status !== 'All') {
    filtered = filtered.filter((w) => w.status === status)
  }

  if (category && category !== 'All') {
    filtered = filtered.filter((w) => w.category === category)
  }

  if (department && department !== 'All') {
    filtered = filtered.filter((w) => w.department === department)
  }

  return filtered
}

