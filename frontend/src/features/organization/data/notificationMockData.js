const now = new Date()
const minsAgo = (m) => {
  const d = new Date(now.getTime() - m * 60000)
  return d.toISOString()
}
const hoursAgo = (h) => minsAgo(h * 60)
const daysAgo = (d) => {
  const dt = new Date(now.getTime() - d * 86400000)
  return dt.toISOString()
}

const timeAgo = (iso) => {
  const parsed = new Date(normalizeNotificationTimestamp(iso)).getTime()
  if (!iso || !Number.isFinite(parsed)) return 'Date unavailable'
  const diff = Math.max(0, Date.now() - parsed)
  const mins = Math.floor(diff / 60000)
  const hours = Math.floor(mins / 60)
  const days = Math.floor(hours / 24)
  if (mins < 1) return 'Just now'
  if (mins < 60) return `${mins} min${mins > 1 ? 's' : ''} ago`
  if (hours < 24) return `${hours} hour${hours > 1 ? 's' : ''} ago`
  if (days < 7) return `${days} day${days > 1 ? 's' : ''} ago`
  return new Date(normalizeNotificationTimestamp(iso)).toLocaleDateString('en-US', { month: 'short', day: 'numeric' })
}

const formatTime = (iso) => {
  const parsed = new Date(normalizeNotificationTimestamp(iso))
  if (!iso || !Number.isFinite(parsed.getTime())) return 'Date unavailable'
  return parsed.toLocaleString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  })
}

