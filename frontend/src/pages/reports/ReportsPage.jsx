/* Decorative chart drawn in the corner of each report card. */
function ReportChart({ kind, color }) {
  if (kind === "line" || kind === "area") {
    return (
      <svg className="mv15-report__chart mv15-report__chart--line" viewBox="0 0 200 80" preserveAspectRatio="none" aria-hidden="true">
        <path d="M0 76 C28 70 40 50 62 56 C84 62 96 36 118 42 C140 48 152 18 176 22 C188 24 194 14 200 10 V80 H0 Z" fill={color} fillOpacity={kind === "area" ? ".22" : ".1"} />
        <path d="M0 76 C28 70 40 50 62 56 C84 62 96 36 118 42 C140 48 152 18 176 22 C188 24 194 14 200 10" fill="none" stroke={color} strokeWidth="3" vectorEffect="non-scaling-stroke" />
        <circle cx="200" cy="10" r="4" fill={color} />
      </svg>
    );
  }
  const heights = kind === "bars-tall" ? [22, 34, 30, 48, 40, 58] : [16, 28, 22, 40, 54, 36];
  return (
    <svg className="mv15-report__chart" viewBox="0 0 120 64" aria-hidden="true">
      {heights.map((height, index) => (
        <rect key={index} x={4 + index * 19} y={62 - height} width="12" height={height} rx="2" fill={color} fillOpacity={0.35 + index * 0.1} />
      ))}
    </svg>
  );
}

function DailyReport({ batch, submitted, onClose, onSubmit }) {
  const [completed, setCompleted] = useState([
    "React Hooks explained and practice exercise completed.",
  ]);
  const [pending, setPending] = useState([
    "Share recording with absent students.",
  ]);
  const [plan, setPlan] = useState(
    "Continue with React Context API and complete the lab exercise.",
  );
  const add = (setter) => setter((items) => [...items, ""]);
  const update = (setter, items, index, value) =>
    setter(items.map((item, i) => (i === index ? value : item)));
  const canSubmit = useMemo(
    () => completed.some((item) => item.trim()) && plan.trim(),
    [completed, plan],
  );
  return (
    <div
      className="fixed inset-0 z-[90] flex justify-end bg-slate-950/35"
      onMouseDown={onClose}
    >
      <section
        onMouseDown={(e) => e.stopPropagation()}
        className="h-full w-full max-w-[620px] overflow-y-auto bg-white p-6 shadow-2xl dark:bg-slate-900"
      >
        <h2 className="text-xl font-bold text-slate-950 dark:text-white">
          Daily class report
        </h2>
        <p className="mt-1 text-sm text-slate-500">
          {submitted
            ? "Submitted — this report is locked for editing."
            : `Aug 4, 2026 · Rahul Sharma · ${batch}`}
        </p>
        {submitted ? (
          <div className="mt-6 rounded-xl bg-emerald-50 p-4 text-sm font-medium text-emerald-700">
            This report has been submitted to the Academic Coordinator.
          </div>
        ) : (
          <div className="mt-6 space-y-5">
            <Field label="Topic covered">
              <input defaultValue="React Hooks" className="field" />
            </Field>
            <Field label="Class duration">
              <input defaultValue="1 hour 30 minutes" className="field" />
            </Field>
            <Field label="Students present / absent">
              <input defaultValue="24 present · 4 absent" className="field" />
            </Field>
            <Rows
              label="Today’s completed work"
              items={completed}
              setItems={setCompleted}
              add={add}
              update={update}
            />
            <Rows
              label="Pending work"
              items={pending}
              setItems={setPending}
              add={add}
              update={update}
            />
            <Field label="Students needing attention">
              <select className="field">
                <option>Pooja Singh — low attendance</option>
                <option>Arjun Kumar — attendance issue</option>
                <option>No additional students</option>
              </select>
            </Field>
            <Field label="Next class plan">
              <textarea
                value={plan}
                onChange={(e) => setPlan(e.target.value)}
                rows={4}
                className="field"
              />
            </Field>
          </div>
        )}
        <div className="mt-6 flex gap-2">
          <button
            onClick={onClose}
            className="rounded-xl border border-slate-200 px-4 py-2.5 text-sm font-semibold"
          >
            Close
          </button>
          {!submitted && (
            <>
              <button
                onClick={() => toast.success("Daily report saved as draft.")}
                className="rounded-xl border border-slate-200 px-4 py-2.5 text-sm font-semibold"
              >
                Save draft
              </button>
              <button
                disabled={!canSubmit}
                onClick={onSubmit}
                className="inline-flex items-center gap-2 rounded-xl bg-[#0F55F7] px-4 py-2.5 text-sm font-semibold text-white disabled:opacity-50"
              >
                <Send size={16} />
                Submit to Academic Coordinator
              </button>
            </>
          )}
        </div>
      </section>
    </div>
  );
}
function Field({ label, children }) {
  return (
    <label className="block text-sm font-semibold text-slate-700 dark:text-slate-200">
      {label}
      <div className="mt-1.5">{children}</div>
    </label>
  );
}
function Rows({ label, items, setItems, add, update }) {
  return (
    <div>
      <p className="text-sm font-semibold text-slate-700 dark:text-slate-200">
        {label}
      </p>
      <div className="mt-1.5 space-y-2">
        {items.map((item, index) => (
          <input
            key={index}
            value={item}
            onChange={(e) => update(setItems, items, index, e.target.value)}
            className="field"
            placeholder="Add an item"
          />
        ))}
      </div>
      <button
        onClick={() => add(setItems)}
        className="mt-2 inline-flex items-center gap-1 text-xs font-semibold text-[#0F55F7]"
      >
        <Plus size={14} />
        Add item
      </button>
    </div>
  );
}
